#!/usr/bin/env python3
r"""
make_elsarticle.py -- build the ISA Transactions submission in elsarticle format.

Produces a single-column, 12 pt, double-spaced, line-numbered manuscript with
no author block, no acknowledgments and no identifying repository URL, as
required for double-anonymized review.

Usage (from the repository root):

    python3 scripts/make_elsarticle.py
    python3 scripts/make_elsarticle.py --src article/main.tex \
                                       --out submission/isa_manuscript.tex

The output needs elsarticle.cls and elsarticle-num.bst beside it (both ship
with TeX Live; copies are also in the Elsevier template package).

After building:

    cd submission && pdflatex isa_manuscript && pdflatex isa_manuscript
    pdftotext isa_manuscript.pdf - | grep -icE "clarimar|goi|klug|puc|github"
"""
import argparse, io, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--src", default="article/main.tex")
ap.add_argument("--out", default="submission/isa_manuscript.tex")
ap.add_argument("--journal", default="ISA Transactions")
args = ap.parse_args()

if not os.path.exists(args.src):
    sys.exit(f"ERROR: source not found: {args.src}\nRun from the repository root.")
os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
s = io.open(args.src, encoding="utf-8").read()

TITLE = ("Fault-Onset Labeling Bounds Reported Accuracy in the Tennessee "
         "Eastman Benchmark: A Leakage-Controlled Study of Six Classical "
         "Classifiers")

HIGHLIGHTS = [
    "TEP fault injection at sample 161 caps literal-label recall at 0.833 per fault class",
    "Rescoring the frozen model post-onset raises macro-F1 from 0.720 to 0.805",
    "The validation-to-test gap of +0.048 becomes -0.013 under symmetric labeling",
    "Seven classifiers gain 0.142-0.150 in relative accuracy, near a 0.159 bound",
    "Faults 3, 9, 15 and normal operation remain confounded after the artifact is removed",
]

KEYWORDS = ("Tennessee Eastman Process \\sep fault diagnosis \\sep machine "
            "learning \\sep process monitoring \\sep reproducible benchmark "
            "\\sep fault-onset labeling")

# --- extract abstract -------------------------------------------------------
m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", s, re.S)
if not m:
    sys.exit("ERROR: abstract not found in source.")
abstract = m.group(1).strip()

# --- extract body: everything after the keywords line up to \end{document} ---
body_start = s.find("\\section{Introduction}")
if body_start < 0:
    sys.exit("ERROR: \\section{Introduction} not found.")
body_end = s.rfind("\\end{document}")
body = s[body_start:body_end]

# --- strip what elsarticle supplies or blinding forbids ---------------------
body = body.replace("\\begin{table*}", "\\begin{table}")
body = body.replace("\\end{table*}", "\\end{table}")
body = body.replace("\\begin{figure*}", "\\begin{figure}")
body = body.replace("\\end{figure*}", "\\end{figure}")
body = body.replace("\\balance\n", "")

# tables were laid out for a two-column page; shrink only those that overflow
body = body.replace("\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}",
                    "\\begin{tabular}")
body = body.replace("\\end{tabular}}\n\\end{table}",
                    "\\end{tabular}\n\\end{table}")
# figures were sized for a narrow column; scale for the single-column page
body = body.replace("width=\\columnwidth", "width=0.72\\textwidth")
body = body.replace("width=0.96\\textwidth", "width=0.78\\textwidth")
body = body.replace("width=0.82\\textwidth", "width=0.70\\textwidth")

body = body.replace("\\begin{tabular}", "\\fit{\\begin{tabular}")
body = body.replace("\\end{tabular}", "\\end{tabular}}")

# CRediT names identify the authors: keep the roles, drop the names
body = body.replace("\\textbf{Alexandre Coelho:}", "\\textbf{First author:}")
body = body.replace("\\textbf{Rodrigo Ruzi:}", "\\textbf{Second author:}")
body = body.replace("\\textbf{Clarimar Jos\\'e Coelho:}", "\\textbf{Third author:}")

# acknowledgments identify the authors: remove for review
body = re.sub(r"\\section\*\{Acknowledgments\}.*?(?=\\section\*|\\begin\{thebibliography\})",
              "% Acknowledgments removed for double-anonymized review.\n\n",
              body, flags=re.S)

# repository URL identifies the authors
body = body.replace(
    r"\TBD{repository URL} and archived under \TBD{Zenodo DOI}",
    r"an anonymized repository for peer review, \TBD{anonymous DOI}; "
    r"the non-anonymized repository is cited in the accepted version")

preamble = r"""%% ISA Transactions -- blinded submission (elsarticle)
%% Generated by scripts/make_elsarticle.py -- do not edit by hand.
%% Edit article/main.tex and regenerate.
%% 'review' adds double spacing but pushes past the 30-page limit
\documentclass[preprint,12pt]{elsarticle}

\usepackage{amssymb}
\usepackage{amsmath}
\usepackage{booktabs}
\usepackage{float}
\usepackage{xcolor}
\usepackage{url}
\usepackage{lineno}
\linenumbers

\graphicspath{{figures/}{../article/figures/}}

%% \TBD{} marks values still to be filled. Remove before submission.
\newcommand{\TBD}[1]{\textcolor{red}{\textbf{[TBD:~#1]}}}
\newcommand{\CHECK}[1]{\textcolor{blue}{\textbf{[CO-AUTHORS:~#1]}}}

%% Shrink a table only if it is wider than the text block.
\newcommand{\fit}[1]{%
  \resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{#1}}

\journal{JOURNALNAME}

\begin{document}

\begin{frontmatter}

\title{TITLETEXT}

%% Author block omitted: ISA Transactions uses double-anonymized review.
%% Names, affiliations and the corresponding author go on the separate
%% title page.

\begin{abstract}
ABSTRACTTEXT
\end{abstract}

\begin{keyword}
KEYWORDSTEXT
\end{keyword}

\end{frontmatter}

"""

preamble = (preamble
            .replace("JOURNALNAME", args.journal)
            .replace("TITLETEXT", TITLE)
            .replace("ABSTRACTTEXT", abstract)
            .replace("KEYWORDSTEXT", KEYWORDS))

out = preamble + body + "\n\\end{document}\n"
io.open(args.out, "w", encoding="utf-8").write(out)

# ISA Transactions asks for highlights as a separate file
hpath = os.path.join(os.path.dirname(args.out) or ".", "highlights.txt")
io.open(hpath, "w", encoding="utf-8").write("\n".join(HIGHLIGHTS) + "\n")
print("Wrote", hpath)

print("Wrote", args.out)
print("  source     :", args.src)
print("  highlights :", len(HIGHLIGHTS),
      "(max chars:", max(len(h) for h in HIGHLIGHTS), ")")
print("  TBD markers:", out.count("\\TBD{") - 1)
for h in HIGHLIGHTS:
    if len(h) > 85:
        print(f"  WARNING: highlight over 85 chars ({len(h)}): {h}")
